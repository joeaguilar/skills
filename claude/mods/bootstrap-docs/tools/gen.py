"""Regenerates hooks/templates.ts and tests/reference.ts from bootstrap_project_docs.py.

    python tools/gen.py <path to bootstrap_project_docs.py> <scratch dir>

templates.ts is built from the script's own docs() table, so the mod carries the
same text without running python. reference.ts is what the script really wrote
when run as a program (CRLF folded to LF: on Windows python's text mode writes
CRLF, and the mod writes LF everywhere), which the tests hold the port to.
"""

from __future__ import annotations

import importlib.util
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
SENTINEL = "\x00PROJECT\x00"
RUNS = {"scratch-project": [], "My Project": ["--project-name", "My Project"]}


def quoted(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def line_of(line: str) -> str:
    parts = line.split(SENTINEL)
    if len(parts) == 1:
        return quoted(line)
    pieces: list[str] = []
    for at, part in enumerate(parts):
        if at > 0:
            pieces.append("projectName")
        if part:
            pieces.append(quoted(part))
    return " + ".join(pieces)


def main() -> int:
    script = Path(sys.argv[1]).resolve()
    scratch = Path(sys.argv[2]).resolve()

    spec = importlib.util.spec_from_file_location("bootstrap_project_docs", script)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    docs: dict[str, str] = module.docs(SENTINEL)

    out = [
        "// Generated by tools/gen.py from bootstrap_project_docs.py: edit the script, then regenerate.",
        "// The text of each file is the script's own, line for line, ending in one newline.",
        "",
        "/** The scaffold's files with their content, in the order the script writes them. */",
        "export const docsOf = (projectName: string): readonly (readonly [name: string, content: string])[] => [",
    ]
    for name, content in docs.items():
        assert content.endswith("\n") and "\r" not in content
        out.append("  [")
        out.append(f"    {quoted(name)},")
        out.append("    [")
        for line in content[:-1].split("\n"):
            out.append(f"      {line_of(line)},")
        out.append("    ].join('\\n') + '\\n',")
        out.append("  ],")
    out.append("]")
    out.append("")
    (HERE / "hooks" / "templates.ts").write_text("\n".join(out), encoding="utf-8", newline="\n")

    ref = [
        "// Generated by tools/gen.py: what bootstrap_project_docs.py wrote when run as a program,",
        "// its line endings folded to LF. Keyed by the README heading each run produced.",
        "",
        "export const REFERENCE: Record<string, Record<string, string>> = {",
    ]
    for heading, flags in RUNS.items():
        target = scratch / ("scratch-project" if not flags else "named")
        subprocess.run([sys.executable, str(script), str(target), *flags], check=True, capture_output=True)
        ref.append(f"  {quoted(heading)}: {{")
        for path in sorted(target.iterdir()):
            text = path.read_bytes().decode("utf-8").replace("\r\n", "\n")
            ref.append(f"    {quoted(path.name)}: {quoted(text)},")
        ref.append("  },")
    ref.append("}")
    ref.append("")
    (HERE / "tests" / "reference.ts").write_text("\n".join(ref), encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
